import Foundation
import MediaServices
import Persistence
import ProjectDomain
import RenderEngine

/// Builds the demo project from generated media. Nothing is bundled or downloaded, so the demo has
/// no licensing strings attached and doubles as an end-to-end smoke test.
public enum DemoBuilder {
    public struct Result: Sendable {
        public var projectURL: URL
        public var mediaFolder: URL
        public var sequences: [String]
    }

    public static func build(in directory: URL, name: String = "Kirie Demo") async throws -> Result {
        let manager = FileManager.default
        try manager.createDirectory(at: directory, withIntermediateDirectories: true)
        let media = directory.appendingPathComponent("Demo Media", isDirectory: true)
        try manager.createDirectory(at: media, withIntermediateDirectories: true)
        let projectURL = directory.appendingPathComponent("\(name).\(ProjectPackage.fileExtension)")
        if manager.fileExists(atPath: projectURL.path) { throw PersistenceError.alreadyExists(projectURL.lastPathComponent) }

        // Generated media.
        let coral = RGBAColor(r: 0.89, g: 0.42, b: 0.38), indigo = RGBAColor(r: 0.29, g: 0.33, b: 0.72), teal = RGBAColor(r: 0.18, g: 0.58, b: 0.56)
        let clips: [(String, RGBAColor, Double?)] = [("Clip A.mov", coral, 330), ("Clip B.mov", indigo, nil), ("Clip C.mov", teal, nil)]
        for (file, color, tone) in clips {
            try await SampleMedia.writeTestVideo(to: media.appendingPathComponent(file), width: 540, height: 960, seconds: 4, color: color,
                                                 label: String(file.prefix(6)), toneFrequency: tone)
        }
        try SampleMedia.writeClickTrack(to: media.appendingPathComponent("Beat 120.wav"), bpm: 120, seconds: 16)
        try SampleMedia.writeComicStrip(to: media.appendingPathComponent("Strip.png"))
        let lineColors = [RGBAColor(r: 0.98, g: 0.92, b: 0.80), RGBAColor(r: 0.85, g: 0.92, b: 0.98), RGBAColor(r: 0.98, g: 0.86, b: 0.88)]
        for (index, color) in lineColors.enumerated() {
            try SampleMedia.writeStill(to: media.appendingPathComponent("Line \(index + 1).png"), color: color, label: "line \(index + 1)")
        }

        let session = try ProjectSession.create(at: projectURL, name: name, canvas: CanvasSettings(width: 1080, height: 1920, frameRate: .fps30))
        let imported = try await session.importFiles([media], actor: .system)
        guard imported.failures.isEmpty else {
            throw ServiceError.invalid("Demo media could not be imported: \(imported.failures.map(\.reason).joined(separator: " "))")
        }
        func asset(_ name: String) throws -> MediaAsset {
            guard let found = session.project.assets.first(where: { $0.name == name }) else { throw ServiceError.notFound(name) }
            return found
        }
        let beat = try asset("Beat 120.wav")
        try session.execute(.updateAssetInfo(assetID: beat.id, name: nil, rights: RightsInfo(status: .owned, title: "Demo beat", source: "Generated by Kirie"),
                                             favourite: nil, rating: nil, keywords: ["demo"], bpm: 120), actor: .system)

        // 1. A reel: three clips cut to the beat, with a title, captions and transitions.
        let reelID = session.project.activeSequenceID
        try session.execute(.renameSequence(sequenceID: reelID, name: "Reel"), actor: .system)
        var clipIDs: [UUID] = []
        for name in ["Clip A.mov", "Clip B.mov", "Clip C.mov"] {
            let id = UUID()
            try session.execute(.addClip(sequenceID: nil, clipID: id, assetID: try asset(name).id, trackID: nil, start: nil, sourceStart: nil,
                                         duration: RationalTime(seconds: 3), index: nil), actor: .system)
            clipIDs.append(id)
        }
        let songClip = UUID()
        try session.execute(.addClip(sequenceID: nil, clipID: songClip, assetID: beat.id, trackID: nil, start: .zero, sourceStart: nil,
                                     duration: RationalTime(seconds: 9), index: nil), actor: .system)
        let (beatCommand, _) = try await session.beatMarkersCommand(forClip: songClip)
        try session.execute(beatCommand, actor: .system)
        try session.execute(.setTransition(clipID: clipIDs[1], transition: Transition(type: .dissolve, duration: RationalTime(seconds: 0.4))), actor: .system)
        try session.execute(.setTransition(clipID: clipIDs[2], transition: Transition(type: .slide, duration: RationalTime(seconds: 0.4), direction: .up)), actor: .system)
        try session.execute(.cutToBeat(clipIDs: clipIDs, every: 4), actor: .system)
        try session.execute(.setClipAudio(clipID: clipIDs[0], audio: ClipAudio(gain: 0.35, fadeOut: RationalTime(seconds: 0.5))), actor: .system)
        var title = Clip(kind: .text, name: "Title", start: RationalTime(seconds: 0.2), duration: RationalTime(seconds: 1.6),
                         text: TextContent(string: "Made with Kirie", style: TextStyle(fontSize: 96), animation: .pop))
        title.transform.position = UnitPoint2D(x: 0.5, y: 0.16)
        try session.execute(.insertClip(sequenceID: nil, trackID: nil, clip: title, index: nil), actor: .system)
        let captions = [
            CaptionSegment(start: RationalTime(seconds: 0.5), end: RationalTime(seconds: 2.4), text: "Three clips, cut to the beat"),
            CaptionSegment(start: RationalTime(seconds: 2.6), end: RationalTime(seconds: 4.4), text: "Captions you can restyle"),
            CaptionSegment(start: RationalTime(seconds: 4.6), end: RationalTime(seconds: 6), text: "Exported with no watermark"),
        ]
        try session.execute(.replaceCaptions(sequenceID: nil, trackID: UUID(), segments: captions, style: .caption, animation: .karaoke), actor: .system)

        // 2. Comic Studio: a strip, reviewed and approved, and its panel-by-panel reel.
        let strip = try session.addStrip(assetID: try asset("Strip.png").id, number: 1, slug: "demo strip")
        try session.execute(.comic(.setSynopsis(synopsis: Synopsis(
            premise: "Two friends plan a quiet afternoon.", panelLines: ["A plan is made.", "The snacks arrive.", "So does the cat.", "Nobody gets a snack."],
            punchline: "The cat wins.", cast: "Two friends and a cat"))), actor: .system)
        for (index, panel) in strip.panels.enumerated() {
            let review = PanelReview(status: .pass, strangerNote: "Demo panel \(index + 1): one figure on a flat tinted background, numbered in the corner.")
            try session.execute(.comic(.setPanelReview(stripID: strip.id, panelID: panel.id, review: review)), actor: .system)
        }
        for item in session.project.comic?.checklist.items ?? [] {
            try session.execute(.comic(.setCheck(stripID: strip.id, itemID: item.id, result: CheckResult(status: .pass, reason: "Generated demo strip."))), actor: .system)
        }
        try session.execute(.comic(.setEndCard(endCard: EndCard(enabled: true, text: "made with kirie"))), actor: .system)
        try session.approveStrip(stripID: strip.id, approvedBy: "Kirie demo")
        try session.buildStripReel(stripID: strip.id, options: StripReelOptions(varyTransitions: true))

        // 3. A lyric edit on the generated beat.
        let art = try (1...3).map { try asset("Line \($0).png") }
        let lines = [
            LyricLine(start: RationalTime(seconds: 0.25), end: RationalTime(seconds: 4.25), text: "this is the *first* line", style: .verse,
                      shots: [LyricShot(at: RationalTime(seconds: 0.25), assetID: art[0].id)]),
            LyricLine(start: RationalTime(seconds: 4.25), end: RationalTime(seconds: 8.25), text: "stacked / *rows* / rise", style: .stack,
                      shots: [LyricShot(at: RationalTime(seconds: 4.25), assetID: art[1].id, cut: .ghost)]),
            LyricLine(start: RationalTime(seconds: 8.25), end: RationalTime(seconds: 12.25), text: "and the *chorus* / hits", style: .chorus,
                      shots: [LyricShot(at: RationalTime(seconds: 8.25), assetID: art[2].id, cut: .flash),
                              LyricShot(at: RationalTime(seconds: 10.25), assetID: art[2].id, zoom: 1.5, focus: UnitPoint2D(x: 0.5, y: 0.62), cut: .shake)]),
        ]
        try session.execute(.comic(.setLyricEdit(edit: LyricEdit(audioAssetID: beat.id, lines: lines))), actor: .system)
        try session.buildLyricEdit()

        try session.execute(.setActiveSequence(sequenceID: reelID), actor: .system)
        try session.save()
        try session.createSnapshot(name: "Fresh demo")
        return Result(projectURL: session.package.url, mediaFolder: media, sequences: session.project.sequences.map(\.name))
    }
}
